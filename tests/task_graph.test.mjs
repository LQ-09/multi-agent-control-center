import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdir} from 'node:fs/promises';
import {renderToStaticMarkup} from 'react-dom/server';
import React from 'react';
await mkdir('build/tests',{recursive:true});
await build({entryPoints:['src/task-graph.tsx'],outfile:'build/tests/task-graph.mjs',bundle:true,platform:'node',format:'esm',external:['react','react-dom'],jsx:'automatic'});
globalThis.localStorage={getItem:()=>null};
globalThis.document={documentElement:{style:{setProperty(){}},lang:''}};
const {graphLayout,TaskGraph}=await import('../build/tests/task-graph.mjs');
const step=(id,position,dependencies,status='Pending')=>({id,position,dependencies:JSON.stringify(dependencies),task_id:'t',role:position?'Execute':'Plan',agent:'codex',host:'local',status,output:'',instruction:'查找实时价格'});
const steps=[step('plan',0,[],'Succeeded'),step('a',1,['plan'],'Running'),step('b',2,['plan'],'Running'),{...step('end',3,['a','b']),role:'Deliver'}];
const {nodes}=graphLayout(steps);
assert.equal(nodes[1].y,nodes[2].y);assert.notEqual(nodes[1].x,nodes[2].x);
assert.ok(nodes[3].y>nodes[1].y);assert.deepEqual(nodes[3].deps,['a','b']);
const html=renderToStaticMarkup(React.createElement(TaskGraph,{steps}));
assert.equal((html.match(/class="graph-edge/g)||[]).length,4);
assert.match(html,/2 \/ 3/);assert.match(html,/等待前置任务/);assert.match(html,/aria-pressed="false"/);
console.log('PASS: graph branching/join geometry and rendered Chinese states/accessible node controls.');
